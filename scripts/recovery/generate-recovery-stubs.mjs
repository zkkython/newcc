#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const MANIFEST_FILE = path.join(ROOT, 'recovery-manifest.json');

if (!fs.existsSync(MANIFEST_FILE)) {
  console.error('missing recovery-manifest.json, run scan-missing-imports first');
  process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(MANIFEST_FILE, 'utf8'));
const overwrite = process.argv.includes('--overwrite');
const protectedPaths = new Set([
  'src/types/message.ts',
  'src/types/tools.ts',
  'src/types/utils.ts',
  'src/constants/querySource.ts',
  'src/entrypoints/sdk/controlTypes.ts',
]);

function safeIdentifier(name) {
  return /^[A-Za-z_$][\w$]*$/u.test(name);
}

function makeStub(module) {
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/recovery/generate-recovery-stubs.mjs');
  lines.push('// Purpose: unblock compilation for missing module in leaked snapshot recovery.');
  lines.push('');
  lines.push('// A resilient callable+indexable placeholder to reduce runtime hard-crashes.');
  lines.push('type RecoveryCallable = ((...args: any[]) => any) & Record<string, any>;');
  lines.push('const __recoveryFactory = (): RecoveryCallable => {');
  lines.push('  const fn = (() => undefined) as RecoveryCallable;');
  lines.push('  return new Proxy(fn, {');
  lines.push('    get: (_target, key) => (key === Symbol.toStringTag ? \"RecoveryStub\" : __recoveryFactory()),');
  lines.push('    apply: () => undefined,');
  lines.push('    construct: () => ({}),');
  lines.push('  });');
  lines.push('};');
  lines.push('const __recoveryStub: RecoveryCallable = __recoveryFactory();');
  lines.push('');

  let wroteSomething = false;

  for (const raw of module.namedImports || []) {
    if (!safeIdentifier(raw)) continue;
    lines.push(`export type ${raw} = any;`);
    lines.push(`export const ${raw}: any = __recoveryStub;`);
    wroteSomething = true;
  }

  if (module.defaultImport) {
    lines.push('');
    lines.push('const _defaultExport: any = __recoveryStub;');
    lines.push('export default _defaultExport;');
    wroteSomething = true;
  }

  if (!wroteSomething || module.namespaceImport || module.hasDynamicImport) {
    lines.push('');
    lines.push('export const __recovery_stub = true;');
  }

  lines.push('');
  return lines.join('\n');
}

let created = 0;
let skipped = 0;
let existed = 0;
let overwritten = 0;
for (const mod of manifest.missingModules || []) {
  const rel = mod.stubPath;
  if (protectedPaths.has(rel)) {
    skipped += 1;
    continue;
  }
  const abs = path.join(ROOT, rel);
  const existedBefore = fs.existsSync(abs);
  if (existedBefore && !overwrite) {
    existed += 1;
    continue;
  }
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, makeStub(mod), 'utf8');
  if (existedBefore && overwrite) overwritten += 1;
  else created += 1;
}

console.log(JSON.stringify({ created, overwritten, skippedProtected: skipped, alreadyExists: existed }, null, 2));
