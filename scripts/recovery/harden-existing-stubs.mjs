#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'src');
const MARKER = '// AUTO-GENERATED by scripts/recovery/generate-recovery-stubs.mjs';

const protectedPaths = new Set([
  'src/types/message.ts',
  'src/types/tools.ts',
  'src/types/utils.ts',
  'src/constants/querySource.ts',
  'src/entrypoints/sdk/controlTypes.ts',
]);

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.isFile() && /\.(ts|tsx)$/u.test(e.name)) out.push(p);
  }
  return out;
}

function build(names, hasDefault) {
  const lines = [];
  lines.push(MARKER);
  lines.push('// Purpose: runtime-resilient placeholders for leaked snapshot recovery.');
  lines.push('');
  lines.push('type RecoveryCallable = ((...args: any[]) => any) & Record<string, any>;');
  lines.push('const __recoveryFactory = (): RecoveryCallable => {');
  lines.push('  const fn = (() => undefined) as RecoveryCallable;');
  lines.push('  return new Proxy(fn, {');
  lines.push('    get: (_target, key) => (key === Symbol.toStringTag ? "RecoveryStub" : __recoveryFactory()),');
  lines.push('    apply: () => undefined,');
  lines.push('    construct: () => ({}),');
  lines.push('  });');
  lines.push('};');
  lines.push('const __recoveryStub: RecoveryCallable = __recoveryFactory();');
  lines.push('');
  for (const n of names) {
    if (n === '__recovery_stub') continue;
    lines.push(`export type ${n} = any;`);
    lines.push(`export const ${n}: any = __recoveryStub;`);
  }
  if (hasDefault) {
    lines.push('');
    lines.push('const _defaultExport: any = __recoveryStub;');
    lines.push('export default _defaultExport;');
  }
  lines.push('');
  lines.push('export const __recovery_stub = true;');
  lines.push('');
  return lines.join('\n');
}

let hardened = 0;
for (const abs of walk(SRC)) {
  const rel = path.relative(ROOT, abs);
  if (protectedPaths.has(rel)) continue;
  const text = fs.readFileSync(abs, 'utf8');
  if (!text.includes(MARKER)) continue;

  const names = new Set();
  const re = /export\s+(?:type\s+)?(?:const|type|function|class|interface|enum)\s+([A-Za-z_$][\w$]*)/gmu;
  let m;
  while ((m = re.exec(text))) names.add(m[1]);
  const hasDefault = /export\s+default\s+/u.test(text);

  fs.writeFileSync(abs, build([...names].sort(), hasDefault), 'utf8');
  hardened += 1;
}

console.log(JSON.stringify({ hardened }, null, 2));
